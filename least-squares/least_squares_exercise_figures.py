def save(fig, outdir: pathlib.Path, name: str) -> None:
    fig.tight_layout()
    fig.savefig(outdir / name, dpi=DPI)
    plt.close(fig)
    print(f"wrote {outdir / name}")


def fetch(name: str) -> pd.DataFrame:
    try:
        return pd.read_csv(f"https://openmv.net/file/{name}")
    except Exception:
        return pd.read_csv(HERE / name)


class Fit:
    """Straight-line least squares fit with the usual diagnostics."""

    def __init__(self, x, y) -> None:
        self.x, self.y = np.asarray(x, float), np.asarray(y, float)
        self.n = len(self.x)
        self.slope, self.intercept = np.polyfit(self.x, self.y, 1)
        self.fitted = self.intercept + self.slope * self.x
        self.residuals = self.y - self.fitted
        self.dof = self.n - 2
        self.se = np.sqrt((self.residuals ** 2).sum() / self.dof)
        self.centred = self.x - self.x.mean()
        self.sxx = (self.centred ** 2).sum()
        self.hat = 1 / self.n + self.centred ** 2 / self.sxx
        self.r2 = 1 - (self.residuals ** 2).sum() / ((self.y - self.y.mean()) ** 2).sum()

    def prediction_interval(self, x_new, level: float = 0.95):
        x_new = np.asarray(x_new, float)
        fit = self.intercept + self.slope * x_new
        spread = self.se * np.sqrt(1 + 1 / self.n + (x_new - self.x.mean()) ** 2 / self.sxx)
        critical = stats.t.ppf(0.5 + level / 2, df=self.dof)
        return fit, fit - critical * spread, fit + critical * spread

    @property
    def studentized(self):
        internal = self.residuals / (self.se * np.sqrt(1 - self.hat))
        return internal * np.sqrt((self.dof - 1) / (self.dof - internal ** 2))

    @property
    def cooks(self):
        internal = self.residuals / (self.se * np.sqrt(1 - self.hat))
        return internal ** 2 / 2 * self.hat / (1 - self.hat)


def qq_panel(ax, values, label: str) -> None:
    ordered = np.sort(values)
    n = len(ordered)
    quantiles = stats.norm.ppf((np.arange(1, n + 1) - 0.375) / (n + 0.25))
    q_data = np.percentile(values, [25, 75])
    q_norm = stats.norm.ppf([0.25, 0.75])
    slope = (q_data[1] - q_data[0]) / (q_norm[1] - q_norm[0])
    intercept = q_data[0] - slope * q_norm[0]
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(quantiles, ordered, "o", color=BLUE, markersize=5,
            markerfacecolor="none", markeredgewidth=1.3)
    ax.plot(quantiles, intercept + slope * quantiles, color=VERMILLION,
            linewidth=2.5)
    ax.set_xlabel("Normal quantiles")
    ax.set_ylabel(label)


def pairs_plot(frame: pd.DataFrame, outdir: pathlib.Path, name: str,
               size: float = 12) -> None:
    columns = list(frame.columns)
    n = len(columns)
    fig, axes = plt.subplots(n, n, figsize=(size, size))
    for row, y_name in enumerate(columns):
        for col, x_name in enumerate(columns):
            ax = axes[row, col]
            ax.grid(color=GRID, linewidth=0.6)
            if row == col:
                ax.hist(frame[x_name], bins=12, color=BLUE_FILL,
                        edgecolor=BLUE, linewidth=1.0)
            else:
                ax.plot(frame[x_name], frame[y_name], "o", color=BLUE,
                        markersize=3.5, markerfacecolor="none",
                        markeredgewidth=0.9)
            if row == 0:
                ax.set_title(x_name)
            if col == 0:
                ax.set_ylabel(y_name)
            if row != n - 1:
                ax.set_xticklabels([])
            if col != 0 or row == col:
                ax.set_yticklabels([])
            ax.tick_params(labelsize=11)
    save(fig, outdir, name)


def lowess(x, y, frac: float = 0.5, gridsize: int = 80):
    order = np.argsort(x)
    xs, ys = np.asarray(x, float)[order], np.asarray(y, float)[order]
    span = max(2, int(frac * len(xs)))
    grid = np.linspace(xs.min(), xs.max(), gridsize)
    fitted = np.empty_like(grid)
    for i, x0 in enumerate(grid):
        distance = np.abs(xs - x0)
        cutoff = np.sort(distance)[span - 1]
        w = np.clip(1 - (distance / max(cutoff, 1e-12)) ** 3, 0, None) ** 3
        total = w.sum()
        xm, ym = (w * xs).sum() / total, (w * ys).sum() / total
        slope = (w * (xs - xm) * (ys - ym)).sum() / max((w * (xs - xm) ** 2).sum(), 1e-12)
        fitted[i] = ym + slope * (x0 - xm)
    return grid, fitted


