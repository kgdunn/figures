def distillation(outdir: pathlib.Path) -> None:
    tower = fetch("distillation-tower.csv")
    temperature = tower["TempC2"].to_numpy(dtype=float)
    pressure = tower["VapourPressure"].to_numpy(dtype=float)
    model = Fit(temperature, pressure)
    print(f"distillation: n {model.n}, VP = {model.intercept:.1f} "
          f"{model.slope:+.4f} T, R2 {model.r2:.3f}, S_E {model.se:.3f}")

    # 1. Raw data, least squares line, prediction interval band.
    grid = np.linspace(temperature.min(), temperature.max(), 200)
    fit, low, high = model.prediction_interval(grid, level=0.99)
    fig, ax = plt.subplots(figsize=(9, 7))
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(temperature, pressure, "o", color=BLUE, markersize=5,
            markerfacecolor="none", markeredgewidth=1.2)
    ax.plot(grid, fit, color=VERMILLION, linewidth=2.5, label="Least squares fit")
    ax.plot(grid, low, "--", color=VERMILLION, linewidth=1.8,
            label="99% prediction interval")
    ax.plot(grid, high, "--", color=VERMILLION, linewidth=1.8)
    ax.set_xlabel("Tray temperature [°F]")
    ax.set_ylabel("Vapour pressure [kPa]")
    ax.legend(loc="upper right", frameon=False)
    save(fig, outdir, "distillation-least-squares.png")

    # 2. Prediction intervals at three new temperatures.
    new = np.array([430.0, 480.0, 520.0])
    fit_new, low_new, high_new = model.prediction_interval(new)
    for t, f, lo, hi in zip(new, fit_new, low_new, high_new):
        print(f"  T = {t:.0f}: fit {f:.2f}, 95% PI {lo:.2f} to {hi:.2f}")
    fig, ax = plt.subplots(figsize=(9, 7))
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(temperature, pressure, "o", color=BLUE, markersize=5,
            markerfacecolor="none", markeredgewidth=1.2)
    edge = np.array([temperature.min(), temperature.max()])
    ax.plot(edge, model.intercept + model.slope * edge, color=VERMILLION,
            linewidth=2.5)
    ax.errorbar(new, fit_new, yerr=[fit_new - low_new, high_new - fit_new],
                fmt="o", color=ORANGE, markersize=9, capsize=8, elinewidth=2.5,
                capthick=2.5, zorder=5)
    ax.set_title("Visualizing the prediction intervals")
    ax.set_xlabel("Tray temperature [°F]")
    ax.set_ylabel("Vapour pressure [kPa]")
    ax.set_ylim(17, 65)
    save(fig, outdir, "distillation-prediction-interval.png")

    # 3. Vapour pressure against the reciprocal of temperature.
    inverse = 1 / temperature
    model_inv = Fit(inverse, pressure)
    print(f"  inverted model: R2 {model_inv.r2:.3f}, S_E {model_inv.se:.3f}")
    fig, ax = plt.subplots(figsize=(9, 7))
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(inverse, pressure, "o", color=BLUE, markersize=5,
            markerfacecolor="none", markeredgewidth=1.2)
    edge = np.array([inverse.min(), inverse.max()])
    ax.plot(edge, model_inv.intercept + model_inv.slope * edge, color=VERMILLION,
            linewidth=2.5, label="Least squares fit")
    smooth_x, smooth_y = lowess(inverse, pressure, frac=0.4)
    ax.plot(smooth_x, smooth_y, "--", color=GREEN, linewidth=2.2,
            label="LOESS smoother")
    ax.set_xlabel("1 / temperature [1/°F]")
    ax.set_ylabel("Vapour pressure [kPa]")
    ax.legend(loc="upper left", frameon=False)
    save(fig, outdir, "distillation-prediction-inverted-temperature.png")

    # 4. The two q-q plots side by side.
    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    qq_panel(axes[0], model.studentized, "Studentized residuals")
    axes[0].set_title("Model with temperature")
    qq_panel(axes[1], model_inv.studentized, "Studentized residuals")
    axes[1].set_title("Model with inverted temperature")
    save(fig, outdir, "distillation-prediction-qqplots.png")

    # 5. Influence plot for the model built on the first 159 samples.
    build = slice(0, 159)
    model_sub = Fit(temperature[build], pressure[build])
    area = 60 + 3000 * model_sub.cooks
    fig, ax = plt.subplots(figsize=(9, 7))
    ax.grid(color=GRID, linewidth=0.8)
    ax.scatter(model_sub.hat, model_sub.studentized, s=area, facecolors="none",
               edgecolors=BLUE, linewidths=1.6)
    ax.axhline(0, color=GREY, linewidth=1.2)
    for level, colour in ((2, GREEN), (3, VERMILLION)):
        ax.axhline(level, color=colour, linestyle="--", linewidth=1.5)
        ax.axhline(-level, color=colour, linestyle="--", linewidth=1.5)
    ax.axvline(2 * 2 / model_sub.n, color=GREEN, linestyle="--", linewidth=1.5)
    ax.axvline(3 * 2 / model_sub.n, color=VERMILLION, linestyle="--", linewidth=1.5)
    # Name the observations the solution removes.
    for index in (38, 53, 84, 101):
        i = index - 1
        ax.annotate(f"{index}", xy=(model_sub.hat[i], model_sub.studentized[i]),
                    xytext=(model_sub.hat[i], model_sub.studentized[i] + 0.28),
                    ha="center", color=VERMILLION, fontsize=14)
    ax.set_title("Marker area is proportional to Cook's distance")
    ax.set_xlabel("Hat value (leverage)")
    ax.set_ylabel("Studentized residuals")
    save(fig, outdir, "distillation-influence-plot.png")


def kappa_autocorrelation(outdir: pathlib.Path) -> None:
    kappa = fetch("kappa-number.csv")["Kappa"].to_numpy(dtype=float)
    jumps = 5
    subsampled = kappa[::jumps]

    def acf(series, lags: int = 50):
        centred = series - series.mean()
        denominator = (centred ** 2).sum()
        return np.array([1.0] + [float((centred[:-k] * centred[k:]).sum() / denominator)
                                 for k in range(1, lags + 1)])

    full, thinned = acf(kappa), acf(subsampled)
    band = 1.96 / np.sqrt(len(kappa))
    print(f"kappa: lag-1 autocorrelation {full[1]:.3f} raw, "
          f"{thinned[1]:.3f} after subsampling every {jumps}th value")

    fig, axes = plt.subplots(2, 1, figsize=(12, 10))
    for ax, values, title, n in (
        (axes[0], full, "Autocorrelation for the Kappa number variable", len(kappa)),
        (axes[1], thinned,
         f"Autocorrelation after subsampling every {jumps}th value", len(subsampled)),
    ):
        lags = np.arange(len(values))
        ax.grid(color=GRID, linewidth=0.8)
        ax.vlines(lags, 0, values, color=BLUE, linewidth=2)
        ax.axhline(0, color="black", linewidth=1)
        for sign in (1, -1):
            ax.axhline(sign * 1.96 / np.sqrt(n), color=VERMILLION,
                       linestyle="--", linewidth=1.5)
        ax.set_title(title)
        ax.set_ylabel("Autocorrelation")
        ax.set_ylim(-0.25, 1.05)
    axes[-1].set_xlabel("Lag")
    save(fig, outdir, "kappa-number-autocorrelation.png")

    # The same series against itself, at lags 0 to 5.
    fig, axes = plt.subplots(1, jumps + 1, figsize=(20, 4.2))
    for lag, ax in enumerate(axes):
        left = kappa[: len(kappa) - lag] if lag else kappa
        right = kappa[lag:] if lag else kappa
        correlation = float(np.corrcoef(left, right)[0, 1])
        ax.grid(color=GRID, linewidth=0.6)
        ax.plot(left, right, "o", color=BLUE, markersize=2, alpha=0.35)
        grid, fitted = lowess(left, right, frac=0.4, gridsize=40)
        ax.plot(grid, fitted, color=VERMILLION, linewidth=2)
        ax.set_title(f"Lag {lag}: r = {correlation:.2f}", fontsize=15)
        ax.set_xlabel("Kappa$_k$", fontsize=14)
        if lag == 0:
            ax.set_ylabel("Kappa$_{k+\\mathrm{lag}}$", fontsize=14)
        ax.tick_params(labelsize=12)
    save(fig, outdir, "kappa-number-autocorrelation-scatterplots.png")


def bioreactor(outdir: pathlib.Path) -> None:
    bio = fetch("bioreactor-yields.csv")
    numeric = bio.copy()
    # "baffles" is Yes/No; code it so it can go into the model and the plot.
    numeric["baffles"] = (numeric["baffles"].str.strip().str.lower() == "yes").astype(float)
    pairs_plot(numeric, outdir, "bioreactor-scatterplot-matrix.png", size=12)

    predictors = numeric[["temperature", "speed", "baffles"]].to_numpy(dtype=float)
    y = numeric["yield"].to_numpy(dtype=float)
    design = np.column_stack([np.ones(len(y)), predictors])
    coefficients, *_ = np.linalg.lstsq(design, y, rcond=None)
    residuals = y - design @ coefficients
    print("bioreactor: yield = "
          f"{coefficients[0]:.2f} + {coefficients[1]:.3f} temperature "
          f"+ {coefficients[2]:.5f} speed + {coefficients[3]:.2f} baffles")

    fig, ax = plt.subplots(figsize=(8, 7))
    qq_panel(ax, residuals, "Residuals")
    save(fig, outdir, "bioreactor-residuals-qq-plot.png")


def gas_furnace(outdir: pathlib.Path) -> None:
    gas = fetch("gas-furnace.csv")
    rate = gas["InputGasRate"].to_numpy(dtype=float)
    co2 = gas["CO2"].to_numpy(dtype=float)
    model = Fit(rate, co2)
    print(f"gas furnace: CO2 = {model.intercept:.2f} {model.slope:+.3f} rate, "
          f"R2 {model.r2:.4f}, correlation {np.corrcoef(rate, co2)[0, 1]:.3f}")

    fig, ax = plt.subplots(figsize=(8, 7))
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(rate, co2, "o", color=BLUE, markersize=5, markerfacecolor="none",
            markeredgewidth=1.2)
    edge = np.array([rate.min(), rate.max()])
    ax.plot(edge, model.intercept + model.slope * edge, color=VERMILLION,
            linewidth=2.5, label="Least squares fit")
    grid, fitted = lowess(rate, co2, frac=0.4)
    ax.plot(grid, fitted, "--", color=GREEN, linewidth=2.2, label="LOESS smoother")
    ax.set_title("Scatter plot with a smoother and the least squares line")
    ax.set_xlabel("Gas flow rate")
    ax.set_ylabel("CO$_2$")
    ax.legend(loc="upper right", frameon=False)
    save(fig, outdir, "CO2-gas-furnace-raw-data.png")

    fig, ax = plt.subplots(figsize=(8, 7))
    qq_panel(ax, model.studentized, "Studentized residuals")
    save(fig, outdir, "CO2-gas-furnace-residuals.png")


def cheese(outdir: pathlib.Path) -> None:
    cheddar = fetch("cheddar-cheese.csv")
    frame = cheddar[["Acetic", "H2S", "Lactic", "Taste"]]
    print("cheese correlations:")
    print(frame.corr().round(2).to_string())
    pairs_plot(frame, outdir, "cheese-data-correlation.png", size=11)


if __name__ == "__main__":
    outdir = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE
    distillation(outdir)
    kappa_autocorrelation(outdir)
    bioreactor(outdir)
    gas_furnace(outdir)
