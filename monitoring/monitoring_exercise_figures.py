# Control limits are not specification limits
# --------------------------------------------------------------------
def control_versus_specification(outdir: pathlib.Path) -> None:
    size = 4
    capability = 1.7
    width = 0.8
    sigma = width / capability / 6
    centre = 2.0
    lsl, usl = centre - 0.4, centre + 0.4
    lcl = centre - 3 * sigma / np.sqrt(size)
    ucl = centre + 3 * sigma / np.sqrt(size)
    print(f"plastic sheet: sigma {sigma:.4f}, LCL {lcl:.3f}, UCL {ucl:.3f}, "
          f"LSL {lsl:.1f}, USL {usl:.1f}")

    x = np.linspace(lsl - 0.1 * width, usl + 0.1 * width, 1001)
    single = norm.pdf(x, loc=centre, scale=sigma)
    of_the_mean = norm.pdf(x, loc=centre, scale=sigma / np.sqrt(size))

    fig, ax = plt.subplots(figsize=(11, 7))
    ax.plot(x, of_the_mean, color=BLUE, linewidth=3,
            label="Distribution of the subgroup mean")
    ax.plot(x, single, color=GREY, linewidth=2,
            label="Distribution of a single measurement")
    ax.axvline(centre, color="black", linewidth=1)

    top = of_the_mean.max() * 0.8
    for bound, label, colour in ((lsl, "LSL", GREY), (usl, "USL", GREY),
                                 (lcl, "LCL", VERMILLION),
                                 (ucl, "UCL", VERMILLION)):
        ax.vlines(bound, 0, top, color=colour, linewidth=2)
        ax.text(bound, top, label, ha="center", va="bottom", color=colour,
                fontsize=17)

    # Mark each spread with a double-headed arrow at its own height.
    for spread, label in ((sigma, r"$\sigma$"),
                          (sigma / np.sqrt(size), r"$\sigma/\sqrt{n}$")):
        height = norm.pdf(centre + spread, loc=centre,
                          scale=spread if spread == sigma else sigma / np.sqrt(size))
        ax.annotate("", xy=(centre + spread, height), xytext=(centre, height),
                    arrowprops=dict(arrowstyle="<->", color="black", linewidth=1.8))
        ax.text(centre + spread * 1.06, height, f" {label}", ha="left",
                va="center", fontsize=19)

    ax.set_title(r"$\mu = 2.0$")
    ax.set_xlabel("$x$")
    ax.set_yticks([])
    ax.set_xlim(lsl, usl)
    ax.set_ylim(0, of_the_mean.max() * 1.12)
    ax.spines["left"].set_visible(False)
    ax.legend(loc="upper left", frameon=False, fontsize=14)
    save(fig, outdir, "plastic-sheet-control-specification-limits.png")


def monitoring_chart_cycling(outdir: pathlib.Path) -> None:
    """Feed weight that cycles, and a Shewhart chart that hides it.

    The measurements behind the original figure are not recoverable: the
    R script reads a CSV from a path on the author's laptop and writes a
    different filename. This is a seeded reconstruction of the series the
    question describes: 100 consecutive measurements one minute apart,
    cycling in a saw-tooth between roughly 1 and 3 kg/s about a target of
    2 kg/s. Substitute the recorded data here if it turns up.

    The control limits are computed from the series actually plotted,
    and are not tuned to reproduce the ones in the original image (which
    measure at 0.96, 1.94 and 2.91 against the 0.99, 1.91 and 2.83 here).
    Matching the picture would mean choosing the amplitude and noise to
    hit numbers read off a bitmap, which would make the chart agree with
    a figure whose data no longer exists while disagreeing with its own.
    The values are printed on the chart so a reader can check them
    against a run of this script.

    Subgroups are the twenty consecutive, non-overlapping groups of five
    that the solution text describes. For each, the mean and the standard
    deviation with one degree of freedom removed. The centre line is the
    mean of the twenty subgroup means; the limits are three standard
    errors either side, using the mean within-subgroup standard deviation
    corrected for bias, ``3 * mean(s) / (a_n * sqrt(n))``, with
    ``a_n = 0.9400`` at ``n = 5``.
    """
    rng = np.random.default_rng(4)
    n = 100
    size = 5
    target = 2.0
    time = np.arange(1, n + 1)
    # A saw-tooth whose period is close to the subgroup size, which is
    # what lets the subgroup means average the cycle away.
    period = 6.5
    phase = (time % period) / period
    feed = target + 0.85 * (2 * phase - 1) + rng.normal(scale=0.32, size=n)

    xbar, sd = subgroup_stats(feed, size)
    lcl, centre, ucl = shewhart_limits(xbar, sd, size)
    inside = ((xbar >= lcl) & (xbar <= ucl)).sum()
    print(f"cycling: LCL {lcl:.2f}, target {centre:.2f}, UCL {ucl:.2f}; "
          f"{inside} of {len(xbar)} subgroup means inside the limits")

    fig, axes = plt.subplots(2, 1, figsize=(13, 8))

    ax = axes[0]
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(time, feed, "-o", color=BLUE, markersize=5, linewidth=1,
            markerfacecolor="none")
    ax.set_title("Raw data: weight of feed entering")
    ax.set_xlabel("Time-ordered samples")
    ax.set_ylabel("Feed [kg/s]")
    ax.set_ylim(0, 3.8)

    ax = axes[1]
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(np.arange(1, len(xbar) + 1), xbar, "-s", color=BLUE, markersize=6,
            linewidth=1)
    draw_limits(ax, lcl, centre, ucl)
    # Show the values, not just the names: they come out of the data
    # plotted above, so a reader can reproduce them.
    ax.text(0.6, ucl, f" UCL = {ucl:.2f}", color=VERMILLION, va="bottom",
            fontsize=15)
    ax.text(0.6, lcl, f" LCL = {lcl:.2f}", color=VERMILLION, va="top",
            fontsize=15)
    ax.text(len(xbar) + 0.4, centre, f" {centre:.2f}", color=GREEN,
            va="center", fontsize=15)
    ax.set_title("Shewhart chart: weight of feed entering")
    ax.set_xlabel("Time order")
    ax.set_ylabel("Subgroup mean")
    ax.set_xticks(np.arange(2, len(xbar) + 1, 2))
    ax.set_ylim(lcl - 0.35, ucl + 0.35)
    save(fig, outdir, "monitoring-chart-cycling.png")


