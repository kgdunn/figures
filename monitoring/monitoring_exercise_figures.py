"""Exercise figures for the process-monitoring chapter of the PID book.

Thirteen committed PNGs, replacing images previously generated by base-R
scripts (``aeration-rate-monitoring.R``, ``Kappa-number-monitoring.R``,
``CO2-question.R``, ``batch-yield-and-purity-recursive.R``,
``batch-yields-monitoring-assignment4-2010.R``,
``plastic-sheet-control-specification-limits.R``). These serve
``process-monitoring/process-monitoring-exercises.rst``:

- ``aeration-rate-raw-data.png``, ``aeration-CUSUM.png``,
  ``aeration-Shewhart-chart.png``: the aeration rate of a bioreactor
  (https://openmv.net/info/aeration-rate), shown raw, as a CUSUM about
  the phase I median, and as a Shewhart chart of subgroup means.
- ``Kappa-raw-data.png``, ``Kappa-phaseI-first-round.png``,
  ``Kappa-phaseI-second-round.png``, ``Kappa-phaseII-testing.png``: the
  Kappa number of pulp (https://openmv.net/info/kappa-number), with the
  first 2000 observations as phase I and the rest as phase II.
- ``CO2-raw-data.png``, ``CO2-phaseI-first-round.png``: carbon dioxide
  off a gas furnace (https://openmv.net/info/gas-furnace).
- ``batch-yield-phaseI-round-1-Yield.png``,
  ``batch-yield-phaseI-round-2-Yield.png``: two rounds of pruning the
  phase I limits for https://openmv.net/info/batch-yield-and-purity.
- ``batch-yields-monitoring.png``: a Shewhart chart of the bioreactor
  yields in https://openmv.net/info/batch-yields.
- ``plastic-sheet-control-specification-limits.png``: the distribution
  of a single measurement against the distribution of the subgroup mean,
  with the specification limits and the control limits marked, showing
  that the two kinds of limit answer different questions.

Two corrections to the originals:

- The aeration Shewhart chart hard-coded its control limits as 22.1 and
  25.8. They are computed here from the first 200 observations, the same
  window that sets the CUSUM target, and come out at 22.12 and 25.77.
- The Kappa figures were drawn with subgroups of 5, while the solution
  text says 6 and quotes limits (18.26 / 21.73 / 25.21, then
  18.24 / 21.71 / 25.19, from 333 phase I subgroups) that only size 6
  reproduces. These use 6, so the charts agree with the numbers beside
  them.

All datasets are fetched from openmv.net; a local CSV of the same name
next to this script is used as a fallback when offline. The script
prints the limits and counts quoted in the exercise solutions.

Usage
-----
    uv run --with numpy --with pandas --with scipy --with matplotlib python monitoring_exercise_figures.py [output_dir]

Writes the thirteen PNGs into ``output_dir`` (default: this script's own
directory), refreshing the committed images in place.
"""

from __future__ import annotations

import pathlib
import sys

import matplotlib as mpl

mpl.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.special import gamma
from scipy.stats import norm

BLUE = "#0072B2"
GREEN = "#009E73"
ORANGE = "#E69F00"
VERMILLION = "#D55E00"
GREY = "#666666"
NEAR_BLACK = "#222222"
GRID = "#DDDDDD"

DPI = 300
HERE = pathlib.Path(__file__).parent

# These charts are wide and short, so the labels sit a little smaller
# than in the taller main-body monitoring figures.
mpl.rcParams.update(
    {
        "font.size": 16,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.titlesize": 18,
        "axes.labelsize": 18,
        "xtick.labelsize": 16,
        "ytick.labelsize": 16,
        "legend.fontsize": 15,
        "axes.axisbelow": True,
    }
)


def save(fig, outdir: pathlib.Path, name: str) -> None:
    fig.tight_layout()
    fig.savefig(outdir / name, dpi=DPI)
    plt.close(fig)
    print(f"wrote {outdir / name}")


def fetch(name: str) -> pd.DataFrame:
    try:
        return pd.read_csv(f"https://openmv.net/file/{name}")
    except Exception:
        return pd.read_csv(HERE / name)


def a_n(n: int) -> float:
    """Unbiasing constant so that S / a_n estimates sigma without bias."""
    return float(np.sqrt(2) * gamma(n / 2) / (np.sqrt(n - 1) * gamma((n - 1) / 2)))


def subgroup_stats(values: np.ndarray, size: int) -> tuple[np.ndarray, np.ndarray]:
    """Mean and standard deviation within consecutive subgroups."""
    n_groups = len(values) // size
    grouped = values[: n_groups * size].reshape(n_groups, size)
    return grouped.mean(axis=1), grouped.std(axis=1, ddof=1)


def shewhart_limits(xbar, sd, size: int, n_sigma: float = 3.0):
    """Return (LCL, target, UCL) for a chart of subgroup means."""
    target = float(np.mean(xbar))
    half = n_sigma * float(np.mean(sd)) / (a_n(size) * np.sqrt(size))
    return target - half, target, target + half


def draw_limits(ax, lcl: float, target: float, ucl: float) -> None:
    ax.axhline(ucl, color=VERMILLION, linewidth=2)
    ax.axhline(lcl, color=VERMILLION, linewidth=2)
    ax.axhline(target, color=GREEN, linewidth=2)


def chart(outdir, name, x, y, xlabel, ylabel, *, style="-o", limits=None,
          figsize=(12, 5), markersize=4, ylim=None, linewidth=1.2):
    fig, ax = plt.subplots(figsize=figsize)
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(x, y, style, color=BLUE, markersize=markersize, linewidth=linewidth)
    if limits is not None:
        draw_limits(ax, *limits)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    if ylim is not None:
        ax.set_ylim(*ylim)
    save(fig, outdir, name)


# --------------------------------------------------------------------
# Aeration rate
# --------------------------------------------------------------------
def aeration(outdir: pathlib.Path) -> None:
    rate = fetch("aeration-rate.csv")["Aeration"].dropna().to_numpy(dtype=float)
    time = np.arange(1, len(rate) + 1)
    size = 5

    chart(outdir, "aeration-rate-raw-data.png", time, rate,
          "Time (min)", "Aeration rate (L/min)", style="-", figsize=(12, 4.5))

    # CUSUM about the median of the first 200 minutes.
    target = float(np.median(rate[:200]))
    cusum = np.cumsum(rate - target)
    detected = int(time[np.argmax(np.abs(cusum) > 0.5 * np.abs(cusum).max())])
    print(f"aeration: n {len(rate)}, CUSUM target {target:.2f}")

    fig, ax = plt.subplots(figsize=(12, 4.5))
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(time, cusum, color=BLUE, linewidth=1.4)
    ax.axhline(0, color=GREY, linewidth=1.2)
    ax.set_xlabel("Time (min)")
    ax.set_ylabel("CUSUM cumulative deviations")
    save(fig, outdir, "aeration-CUSUM.png")

    # Shewhart chart of subgroup means. The limits come from the same
    # first 200 observations that set the CUSUM target.
    xbar, sd = subgroup_stats(rate, size)
    phase1 = 200 // size
    lcl, centre, ucl = shewhart_limits(xbar[:phase1], sd[:phase1], size)
    print(f"  Shewhart from first {phase1} subgroups: "
          f"LCL {lcl:.2f}, target {centre:.2f}, UCL {ucl:.2f}")

    order = np.arange(1, len(xbar) * size + 1, size)
    fig, ax = plt.subplots(figsize=(12, 4.5))
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(order, xbar, "-s", color=BLUE, markersize=4, linewidth=0.9)
    draw_limits(ax, lcl, centre, ucl)
    # Leave room above and below the control limits. Autoscaling on the
    # data alone puts the limits hard against the frame, which reads as
    # though the chart has been cropped, and leaves the annotation
    # sitting on top of the upper limit.
    span = ucl - lcl
    ax.set_ylim(min(lcl, xbar.min()) - 0.35 * span,
                max(ucl, xbar.max()) + 0.35 * span)
    ax.axvline(275, color=ORANGE, linewidth=2)
    # The line stays orange, which separates it from the vermillion
    # control limits and the green target. The label is near-black: the
    # orange is light enough that text set in it is hard to read against
    # white, and it prints poorly in greyscale. The original set this
    # label in black too.
    ax.annotate("CUSUM detected the problem at t = 275", xy=(290, ucl),
                xytext=(0, 12), textcoords="offset points",
                ha="left", va="bottom", color=NEAR_BLACK, fontsize=15)
    ax.set_xlabel("Time order")
    ax.set_ylabel("Phase II subgroups")
    save(fig, outdir, "aeration-Shewhart-chart.png")


