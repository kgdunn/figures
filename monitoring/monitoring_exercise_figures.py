# --------------------------------------------------------------------
# Batch yield and purity: two rounds of pruning
# --------------------------------------------------------------------
def batch_yield_and_purity(outdir: pathlib.Path) -> None:
    yields = fetch("batch-yield-and-purity.csv")["yield"].to_numpy(dtype=float)
    size = 3
    xbar, sd = subgroup_stats(yields, size)
    span = (xbar.min() - 5, xbar.max() + 5)
    print(f"batch yield and purity: n {len(yields)}, subgroup {size}")

    for round_number in (1, 2):
        lcl, centre, ucl = shewhart_limits(xbar, sd, size)
        outside = (xbar < lcl) | (xbar > ucl)
        print(f"  round {round_number}: LCL {lcl:.2f}, target {centre:.2f}, "
              f"UCL {ucl:.2f}; {outside.sum()} of {len(xbar)} outside")
        chart(outdir, f"batch-yield-phaseI-round-{round_number}-Yield.png",
              np.arange(1, len(xbar) + 1), xbar,
              "Sequence order", f"Phase I subgroups: round {round_number}",
              limits=(lcl, centre, ucl), figsize=(12, 4.5), markersize=4,
              ylim=span)
        xbar, sd = xbar[~outside], sd[~outside]


