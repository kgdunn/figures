# Kappa number
# --------------------------------------------------------------------
def kappa(outdir: pathlib.Path) -> None:
    values = fetch("kappa-number.csv")["Kappa"].to_numpy(dtype=float)
    # The solution text says "I used subgroups of size 6", and the limits
    # it quotes (18.26 / 21.73 / 25.21, then 18.24 / 21.71 / 25.19, from
    # 333 phase I subgroups) only come out at size 6. The R script beside
    # these figures used 5, so the images disagreed with the numbers
    # printed next to them.
    size = 6
    n_phase1 = 2000
    print(f"kappa: n {len(values)}, phase I {n_phase1}, subgroup {size}")

    # 1. All the raw data, split into the two phases.
    fig, ax = plt.subplots(figsize=(12, 4.5))
    ax.grid(color=GRID, linewidth=0.8)
    ax.plot(np.arange(1, len(values) + 1), values, ".", color=BLUE,
            markersize=2, alpha=0.6)
    ax.axvline(n_phase1, color=GREY, linewidth=1.5)
    low = ax.get_ylim()[0]
    # Near-black, for the same reason as the CUSUM label: orange text is
    # too light to read against white. Blue, which the original used,
    # would be lost among the data points here.
    ax.text(n_phase1 / 2, low + 1, "Phase I data", ha="center", color=NEAR_BLACK)
    ax.text(n_phase1 + (len(values) - n_phase1) / 2, low + 1, "Phase II data",
            ha="center", color=NEAR_BLACK)
    ax.set_xlabel("Sequence order")
    ax.set_ylabel("Kappa number: raw data")
    save(fig, outdir, "Kappa-raw-data.png")

    xbar, sd = subgroup_stats(values, size)
    phase1_end = n_phase1 // size

    # 2. Round 1: limits from every phase I subgroup.
    x1, s1 = xbar[:phase1_end], sd[:phase1_end]
    lcl, centre, ucl = shewhart_limits(x1, s1, size)
    outside = (x1 < lcl) | (x1 > ucl)
    print(f"  round 1: LCL {lcl:.2f}, target {centre:.2f}, UCL {ucl:.2f}; "
          f"{outside.sum()} of {len(x1)} subgroups outside")
    chart(outdir, "Kappa-phaseI-first-round.png",
          np.arange(1, len(x1) + 1), x1,
          "Sequence order", "Phase I subgroups: round 1",
          limits=(lcl, centre, ucl), figsize=(12, 4.5), markersize=3)

    # 3. Round 2: drop those subgroups and recompute.
    keep = ~outside
    x2, s2 = x1[keep], s1[keep]
    lcl, centre, ucl = shewhart_limits(x2, s2, size)
    still_out = ((x2 < lcl) | (x2 > ucl)).sum()
    print(f"  round 2: LCL {lcl:.2f}, target {centre:.2f}, UCL {ucl:.2f}; "
          f"{still_out} of {len(x2)} subgroups outside")
    chart(outdir, "Kappa-phaseI-second-round.png",
          np.arange(1, len(x2) + 1), x2,
          "Sequence order", "Phase I subgroups: round 2",
          limits=(lcl, centre, ucl), figsize=(12, 4.5), markersize=3)

    # 4. Phase II, using the phase I limits. The solution refers to
    # "sequence point 80 and 140", so phase II is numbered from 1.
    x_phase2 = xbar[phase1_end:]
    alarms = ((x_phase2 < lcl) | (x_phase2 > ucl)).sum()
    print(f"  phase II: {alarms} of {len(x_phase2)} subgroups outside the "
          f"limits ({100 * alarms / len(x_phase2):.1f}%)")
    chart(outdir, "Kappa-phaseII-testing.png",
          np.arange(1, len(x_phase2) + 1), x_phase2,
          "Sequence order", "Phase II subgroups: testing",
          limits=(lcl, centre, ucl), figsize=(12, 4.5), markersize=3)


